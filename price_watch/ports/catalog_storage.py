"""Storage contracts used by card, history, group and transfer consumers."""
from typing import Protocol
from ..domain.models import TrackedCard, TrackedCardOverview, PriceHistoryPoint, PriceStatistics


class CardStore(Protocol):
    async def add_card(self, marketplace: str, external_id: str, title: str | None = None,
                       url: str | None = None, tags: list[str] | None = None) -> TrackedCard: ...
    async def get_card(self, card_id: int) -> TrackedCardOverview | None: ...
    async def list_cards(self) -> list[TrackedCardOverview]: ...
    async def update_card(self, card_id: int, *, title: str | None = None, url: str | None = None,
                          deals_enabled: bool | None = None, update_title: bool = False,
                          update_url: bool = False, group_id: int | None = None,
                          update_group: bool = False, tags: list[str] | None = None, primary_variant_id: int | None = None) -> TrackedCard | None: ...
    async def set_variant_tracking(self, card_id: int, enabled: bool, variant_id: int | None = None) -> bool: ...
    async def get_variant_image(self, card_id: int, variant_id: int) -> tuple[str | None] | None: ...
    async def get_variants(self, card_id: int) -> list[dict]: ...
    async def delete_card(self, card_id: int) -> bool: ...


class HistoryReader(Protocol):
    async def get_history(self, card_id: int, days: int, page: int = 1,
                          page_size: int = 50, variant_id: int | None = None) -> list[PriceHistoryPoint]: ...
    async def get_chart_points(self, card_id: int, days: int) -> list[PriceHistoryPoint]: ...
    async def count_history(self, card_id: int, days: int, variant_id: int | None = None) -> int: ...
    async def get_statistics(self, card_id: int, days: int, variant_id: int | None = None) -> PriceStatistics: ...


class GroupStore(Protocol):
    async def create_group(self, name: str, card_ids: list[int], tags: list[str] | None = None) -> int: ...
    async def update_group(self, group_id: int, name: str, card_ids: list[int],
                           tags: list[str] | None = None) -> bool: ...
    async def delete_group(self, group_id: int) -> bool: ...


class TransferStore(Protocol):
    async def export_cards(self) -> dict: ...
    async def import_cards(self, cards: list[dict], *, groups: list[dict] | None = None,
                           preview: bool = False) -> dict: ...
