"""Atomic run operations grouped by the needs of their consumers."""
from datetime import datetime
from typing import Callable, Protocol
from marketplace_connector.domain.models import MarketplaceCard
from ..domain.models import CollectionRun, TrackedCard, RunLease

Clock = Callable[[], datetime]


class RunExecutionStore(Protocol):
    async def start_direct_run(self, card_id: int | None = None) -> CollectionRun: ...
    async def cards_for_run(self, run_id: int) -> list[TrackedCard]: ...
    async def touch_run(self, lease: RunLease) -> bool: ...
    async def set_run_current(self, lease: RunLease, card: TrackedCard) -> None: ...
    async def save_result(self, lease: RunLease, card: TrackedCard, snapshot: MarketplaceCard) -> None: ...
    async def record_card_error(self, lease: RunLease, card: TrackedCard, error: dict) -> None: ...
    async def finish_run(self, lease: RunLease) -> CollectionRun: ...
    async def fail_run(self, lease: RunLease, error: dict) -> None: ...


class RunQueueStore(Protocol):
    async def fail_stale_runs(self, older_than: datetime | None = None) -> int: ...
    async def create_due_run(self, now: datetime | None = None) -> CollectionRun | None: ...
    async def create_queued_run(self, card_id: int | None = None) -> CollectionRun: ...
    async def create_retry_run(self, source_run_id: int) -> CollectionRun: ...
    async def claim_next_run(self) -> CollectionRun | None: ...
    async def get_run(self, run_id: int, include_errors: bool = True) -> CollectionRun | None: ...
    async def list_runs(self, page: int = 1, page_size: int = 50) -> list[CollectionRun]: ...


class RunChallengeStore(Protocol):
    async def set_run_waiting(self, lease: RunLease, challenge_type: str, message: str) -> None: ...
    async def get_owned_status(self, lease: RunLease) -> str: ...
    async def continue_run(self, run_id: int) -> CollectionRun | None: ...
