"""Persistence operations used by collection execution."""
from typing import Protocol
from marketplace_connector.domain.models import MarketplaceCard
from ..domain.models import CollectionRun, TrackedCard, RunLease


class PriceWatchRepository(Protocol):
    async def start_direct_run(self, card_id: int | None = None) -> CollectionRun: ...
    async def cards_for_run(self, run_id: int) -> list[TrackedCard]: ...
    async def touch_run(self, lease: RunLease) -> bool: ...
    async def set_run_current(self, lease: RunLease, card: TrackedCard) -> None: ...
    async def save_result(self, lease: RunLease, card: TrackedCard, snapshot: MarketplaceCard) -> None: ...
    async def record_card_error(self, lease: RunLease, card: TrackedCard, error: dict) -> None: ...
    async def finish_run(self, lease: RunLease) -> CollectionRun: ...
    async def fail_run(self, lease: RunLease, error: dict) -> None: ...
