import { expect, test } from '@playwright/test'

for (const shape of ['plain', 'mixed', 'group']) test(`catalog ends at the last result after selection, layout and filtering: ${shape}`, async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto(`/cards?perf=5000&shape=${shape}`)
  await page.getByRole('checkbox', { name: /Выбрать карточку/ }).first().check()
  for (const view of ['Список', 'Сетка']) {
    await page.getByRole('radio', { name: view, exact: true }).click()
    await expect.poll(async () => {
      await page.evaluate(() => window.scrollTo(0, document.documentElement.scrollHeight))
      const last = page.getByRole('checkbox', { name: `Выбрать карточку Тестовый товар ${shape === 'mixed' ? '04998' : '04999'}`, exact: true })
      if (!await last.isVisible()) return 99999
      return last.evaluate(el => document.documentElement.scrollHeight - (el.closest('[data-vrow]')!.getBoundingClientRect().bottom + window.scrollY))
    }, { timeout: 10000, intervals: [100, 200] }).toBeLessThan(80)
    const bulk = page.getByRole('group', { name: 'Действия с выбранными карточками' })
    await expect(bulk).toBeVisible()
    const rect = await bulk.boundingBox()
    expect(rect!.y).toBeGreaterThanOrEqual(0)
    expect(rect!.y).toBeLessThan(20)
    await page.evaluate(() => window.scrollTo(0, 0))
  }
  await page.getByLabel('Поиск по названию или артикулу').fill('04999')
  await expect(page.getByRole('checkbox', { name: 'Выбрать карточку Тестовый товар 04999', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollHeight)).toBeLessThan(1200)
})

test('tags contain wheel scrolling at both edges and release the page when closed', async ({ page }) => {
  await page.goto('/cards?perf=1000&dataset=varied')
  await expect(page.locator('.cards-table__product').first()).toBeVisible()
  // Make the page scrollable while the sidebar remains fixed.
  await page.evaluate(() => window.scrollTo(0, 300))
  await page.getByRole('button', { name: 'Теги', exact: true }).click()
  const popup = page.locator('[data-slot="popover-content"]')
  await expect(popup).toBeVisible()
  await expect.poll(() => popup.evaluate(el => el.scrollHeight > el.clientHeight)).toBe(true)
  const before = await page.evaluate(() => window.scrollY)
  await popup.evaluate(el => { el.scrollTop = el.scrollHeight })
  await popup.hover()
  await page.mouse.wheel(0, 1200)
  await page.waitForTimeout(100)
  expect(await page.evaluate(() => window.scrollY)).toBe(before)
  await popup.evaluate(el => { el.scrollTop = 0 })
  await page.mouse.wheel(0, -1200)
  await page.waitForTimeout(100)
  expect(await page.evaluate(() => window.scrollY)).toBe(before)
  await page.keyboard.press('Escape')
  await expect(popup).toBeHidden()
  await page.locator('[data-catalog-results]').hover()
  await page.mouse.wheel(0, 500)
  await expect.poll(() => page.evaluate(() => window.scrollY)).toBeGreaterThan(before)
})

test('settings, help and product layout preserve their positions and keyboard flow', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/cards')
  const settings = page.getByRole('button', { name: 'Настройки', exact: true })
  await settings.click()
  const panel = page.getByRole('dialog', { name: 'Настройки', exact: true })
  await expect(panel).toBeVisible()
  await expect.poll(async () => { const box = (await panel.boundingBox())!; return box.x + box.width / 2 }).toBe(720)
  const bounds = (await panel.boundingBox())!
  expect(bounds.y + bounds.height / 2).toBeCloseTo(450, 0)
  expect(bounds.height).toBe(680)
  expect(bounds.width).toBe(800)
  await expect(panel.getByRole('heading', { name: 'Перенос данных' })).toBeVisible()
  await expect(panel.getByRole('button', { name: 'Экспорт', exact: true })).toBeVisible()
  await panel.getByRole('button', { name: 'Импорт', exact: true }).click()
  const transfer = page.getByRole('dialog', { name: 'Импорт товаров', exact: true })
  await expect(transfer).toBeVisible()
  await transfer.getByRole('button', { name: 'Отмена', exact: true }).click()
  await expect(panel.getByRole('button', { name: 'Импорт', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(settings).toBeFocused()
  const help = page.getByRole('button', { name: 'Справка: Участие в выгодных', exact: true })
  await help.focus()
  await page.keyboard.press('Space')
  await expect(page.locator('[data-slot="popover-content"]')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(help).toBeFocused()
  await help.click()
  await page.getByRole('heading', { name: 'Товары', exact: true }).click()
  await expect(page.locator('[data-slot="popover-content"]')).toBeHidden()
  await page.getByRole('link', { name: 'Смартфон Samsung Galaxy S24', exact: true }).click()
  const image = await page.locator('.detail-header__image').boundingBox()
  const prices = await page.locator('.price-summary').boundingBox()
  expect(image!.x + image!.width).toBeLessThan(prices!.x)
  expect(image!.width / image!.height).toBeCloseTo(3 / 4, 2)
  expect(image!.y).toBeCloseTo((await page.locator('.detail-header h1').boundingBox())!.y, 0)
  await expect(page.getByRole('heading', { name: 'Измерения', exact: true })).toBeVisible()
  expect((await page.getByRole('link', { name: 'К товарам', exact: true }).boundingBox())!.height).toBeGreaterThanOrEqual(44)
})

for (const width of [1024, 1440]) test(`group surfaces and portrait detail align at ${width}px`, async ({ page }) => {
  await page.setViewportSize({width,height:900})
  await page.goto('/cards?perf=100&shape=group')
  const rowColor = await page.locator('.cards-table__group td').nth(1).evaluate(el => getComputedStyle(el).backgroundColor)
  await page.getByRole('radio',{name:'Сетка',exact:true}).click()
  const header = page.locator('.product-group__header')
  await expect(header).toBeVisible()
  expect(await header.evaluate(el => getComputedStyle(el).backgroundColor)).toBe(rowColor)
  const heading = await header.locator('.product-group__heading').boundingBox()
  const metrics = await header.locator('.product-group__metrics').boundingBox()
  expect(metrics!.x - (heading!.x + heading!.width)).toBe(width===1024?12:14)
  expect(await header.locator('.product-group__heading').evaluate(el => getComputedStyle(el).backgroundColor)).toBe('rgba(0, 0, 0, 0)')
  await page.goto('/cards/1')
  await expect(page.getByRole('heading',{name:'Измерения',exact:true})).toBeVisible()
  const image = (await page.locator('.detail-header__image').boundingBox())!
  const prices = (await page.locator('.price-summary').boundingBox())!
  expect(image.x+image.width).toBeLessThan(prices.x)
  expect(image.width/image.height).toBeCloseTo(.75,2)
  expect(image.y).toBeCloseTo((await page.locator('.detail-header h1').boundingBox())!.y,0)
  expect(image.width).toBeGreaterThanOrEqual(216)
  expect(image.height).toBeLessThanOrEqual(360)
  expect(prices.height).toBeLessThan(180)
  const cells = await page.locator('.price-summary__primary, .price-stat').evaluateAll(elements => elements.map(el => { const r = el.getBoundingClientRect(); return { x: r.x, right: r.right, top: r.top, bottom: r.bottom } }))
  expect(cells).toHaveLength(5)
  for (let index = 1; index < cells.length; index++) {
    expect(cells[index].x).toBeGreaterThanOrEqual(cells[index - 1].right)
    expect(cells[index].top).toBeLessThan(cells[0].bottom)
    expect(cells[index].bottom).toBeGreaterThan(cells[0].top)
  }
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
})


test('tiles have edge-to-edge portrait media and savings first; list headings fit', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/cards')
  for (const name of ['Минимальная', 'Маркетплейс']) {
    const heading = page.getByRole('button', { name, exact: true })
    expect(await heading.locator('span').evaluate(el => el.getClientRects().length)).toBe(1)
    expect(await heading.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  }
  await page.getByRole('button', { name: 'Маркетплейс', exact: true }).click()
  const sort = page.getByRole('combobox', { name: 'Сортировка', exact: true })
  await expect(sort).toContainText('по возрастанию')
  expect(await sort.evaluate(el => { const value = el.querySelector('[data-slot=select-value]')!; const range = document.createRange(); range.selectNodeContents(value); return range.getBoundingClientRect().width <= value.getBoundingClientRect().width })).toBe(true)
  await page.getByRole('radio', { name: 'Сетка', exact: true }).click()
  const tile = page.locator('.cards-grid__item').first()
  const box = (await tile.boundingBox())!
  const media = (await tile.locator('.cards-grid__media').boundingBox())!
  expect(media.x - box.x).toBeCloseTo(1, 0)
  expect(media.y - box.y).toBeCloseTo(1, 0)
  expect(box.width - media.width).toBeCloseTo(2, 0)
  expect(media.width / media.height).toBeCloseTo(.75, 2)
  const first = tile.locator('.cards-grid__prices > div').first()
  await expect(first.locator('dt')).toHaveText('Выгода / макс.')
  const current = (await first.locator('.catalog-savings > span').first().boundingBox())!
  const maximum = (await first.locator('.catalog-savings__maximum').boundingBox())!
  expect(maximum.x).toBeGreaterThanOrEqual(current.x + current.width)
  expect(maximum.y).toBeLessThan(current.y + current.height)
})

