import { expect, test } from '@playwright/test'

for (const shape of ['plain', 'mixed', 'group']) test(`catalog ends at the last result after selection, layout and filtering: ${shape}`, async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto(`/cards?perf=5000&shape=${shape}`)
  await page.getByRole('checkbox', { name: /Выбрать карточку/ }).first().check()
  for (const view of ['Список', 'Сетка']) {
    await page.getByRole('radio', { name: view, exact: true }).click()
    await expect.poll(async () => {
      await page.evaluate(() => window.scrollTo(0, document.documentElement.scrollHeight))
      const last = page.getByRole('checkbox', { name: `Выбрать карточку Тестовый товар ${shape === 'mixed' ? '04998' : '04999'}`, exact: true })
      if (!await last.isVisible()) return 99999
      return last.evaluate(el => document.documentElement.scrollHeight - (el.closest('[data-vrow]')!.getBoundingClientRect().bottom + window.scrollY))
    }, { timeout: 10000, intervals: [100, 200] }).toBeLessThan(80)
    const bulk = page.getByRole('group', { name: 'Действия с выбранными карточками' })
    await expect(bulk).toBeVisible()
    const rect = await bulk.boundingBox()
    expect(rect!.y).toBeGreaterThanOrEqual(0)
    expect(rect!.y).toBeLessThan(20)
    await page.evaluate(() => window.scrollTo(0, 0))
  }
  await page.getByLabel('Поиск по названию или артикулу').fill('04999')
  await expect(page.getByRole('checkbox', { name: 'Выбрать карточку Тестовый товар 04999', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollHeight)).toBeLessThan(1200)
})

test('tags contain wheel scrolling at both edges and release the page when closed', async ({ page }) => {
  await page.goto('/cards?perf=1000&dataset=varied')
  await expect(page.locator('.cards-table__product').first()).toBeVisible()
  // Make the page scrollable while the sidebar remains fixed.
  await page.evaluate(() => window.scrollTo(0, 300))
  await page.getByRole('button', { name: 'Теги', exact: true }).click()
  const popup = page.locator('[data-slot="popover-content"]')
  await expect(popup).toBeVisible()
  await expect.poll(() => popup.evaluate(el => el.scrollHeight > el.clientHeight)).toBe(true)
  const before = await page.evaluate(() => window.scrollY)
  await popup.evaluate(el => { el.scrollTop = el.scrollHeight })
  await popup.hover()
  await page.mouse.wheel(0, 1200)
  await page.waitForTimeout(100)
  expect(await page.evaluate(() => window.scrollY)).toBe(before)
  await popup.evaluate(el => { el.scrollTop = 0 })
  await page.mouse.wheel(0, -1200)
  await page.waitForTimeout(100)
  expect(await page.evaluate(() => window.scrollY)).toBe(before)
  await page.keyboard.press('Escape')
  await expect(popup).toBeHidden()
  await page.locator('[data-catalog-results]').hover()
  await page.mouse.wheel(0, 500)
  await expect.poll(() => page.evaluate(() => window.scrollY)).toBeGreaterThan(before)
})

test('settings, help and product layout preserve their positions and keyboard flow', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/cards')
  const settings = page.getByRole('button', { name: 'Настройки', exact: true })
  await settings.click()
  const panel = page.getByRole('dialog', { name: 'Настройки', exact: true })
  await expect(panel).toBeVisible()
  await expect.poll(async () => (await panel.boundingBox())!.x).toBe(260)
  await panel.getByRole('button', { name: 'Импорт', exact: true }).click()
  const transfer = page.getByRole('dialog', { name: 'Импорт товаров', exact: true })
  await expect(transfer).toBeVisible()
  await transfer.getByRole('button', { name: 'Отмена', exact: true }).click()
  await expect(panel.getByRole('button', { name: 'Импорт', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(settings).toBeFocused()
  const help = page.getByRole('button', { name: 'Справка: Участие в выгодных', exact: true })
  await help.focus()
  await page.keyboard.press('Space')
  await expect(page.locator('[data-slot="popover-content"]')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(help).toBeFocused()
  await help.click()
  await page.getByRole('heading', { name: 'Товары', exact: true }).click()
  await expect(page.locator('[data-slot="popover-content"]')).toBeHidden()
  await page.getByRole('link', { name: 'Смартфон Samsung Galaxy S24', exact: true }).click()
  const image = await page.locator('.detail-header__image').boundingBox()
  const prices = await page.locator('.price-summary').boundingBox()
  expect(prices!.x + prices!.width).toBeLessThan(image!.x)
  await expect(page.getByRole('heading', { name: 'Измерения', exact: true })).toBeVisible()
  expect((await page.getByRole('link', { name: 'К товарам', exact: true }).boundingBox())!.height).toBeGreaterThanOrEqual(44)
})
