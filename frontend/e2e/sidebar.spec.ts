import { expect, test } from '@playwright/test'

async function choose(page: import('@playwright/test').Page, control: string, option: string) {
  await page.getByRole('combobox', { name: control, exact: true }).click()
  await page.getByRole('option', { name: option, exact: true }).click()
}

async function selectMany(page: import('@playwright/test').Page, control: string, labels: string[]) {
  await page.getByRole('button', { name: control, exact: true }).click()
  const group = page.getByRole('group', { name: control, exact: true })
  for (const label of labels) await group.getByRole('checkbox', { name: label, exact: true }).check()
  const options = control === 'Маркетплейсы' ? ['Ozon', 'Wildberries', 'AliExpress', 'Яндекс Маркет'] : ['Для дома', 'Для себя', 'Подарки', 'Электроника']
  for (const label of options.filter(label => !labels.includes(label))) await group.getByRole('checkbox', { name: label, exact: true }).uncheck()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: control, exact: true })).toBeFocused()
}

