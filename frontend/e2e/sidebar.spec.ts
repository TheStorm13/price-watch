  await expect(rows.last()).toContainText('Dyson')
  await page.reload()
  await expect(first).not.toBeChecked()
  await expect(rows.nth(1)).toContainText('LEGO')
  await page.getByRole('radio', { name: 'Сетка', exact: true }).click()
