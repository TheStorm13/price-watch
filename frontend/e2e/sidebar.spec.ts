import { expect, test } from '@playwright/test'

async function choose(page: import('@playwright/test').Page, control: string, option: string) {
  await page.getByRole('combobox', { name: control, exact: true }).click()
  await page.getByRole('option', { name: option, exact: true }).click()
}

async function selectMany(page: import('@playwright/test').Page, control: string, labels: string[]) {
  await page.getByRole('button', { name: control, exact: true }).click()
  const group = page.getByRole('group', { name: control, exact: true })
  for (const label of labels) await group.getByRole('checkbox', { name: label, exact: true }).check()
  const options = control === 'Маркетплейсы' ? ['Ozon', 'Wildberries', 'AliExpress', 'Яндекс Маркет'] : ['Для дома', 'Для себя', 'Подарки', 'Электроника']
  for (const label of options.filter(label => !labels.includes(label))) await group.getByRole('checkbox', { name: label, exact: true }).uncheck()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: control, exact: true })).toBeFocused()
}

test('группы фильтруют участников, меняют представителя и считают товары независимо от сворачивания и галочек', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/cards?fixture=catalog')
  const main = page.getByRole('main')
  await expect(main).toContainText('Выбрано 7 из 7 товаров')
  await page.getByRole('button', { name: 'Создать группу', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Создать группу', exact: true })
  await dialog.getByRole('textbox', { name: 'Название', exact: true }).fill('Контейнер')
  for (const name of [/Samsung/, /Dyson/, /234567890/]) await dialog.getByRole('checkbox', { name }).check()
  await dialog.getByRole('button', { name: 'Сохранить', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  const group = main.locator('.cards-table__group').filter({ hasText: 'Контейнер' })
  const toggle = group.locator('.product-group__toggle')
  await expect(group).toContainText('3 из 3 товаров')
  await expect(group.locator('.price-cell').first()).toHaveText(/72\s*990/)
  await expect(main).toContainText('Выбрано 7 из 7 товаров')
  await main.getByRole('checkbox', { name: /Samsung/ }).check()
  await toggle.click()
  await expect(main.getByRole('link', { name: /Samsung/ })).toHaveCount(0)
  await expect(main).toContainText('Выбрано 7 из 7 товаров')
  await choose(page, 'Сортировка', 'Сначала дешёвые')
  await expect(group.locator('.price-cell').first()).toHaveText(/27\s*990/)
  await choose(page, 'Сортировка', 'Сначала дорогие')
  await expect(group.locator('.price-cell').first()).toHaveText(/72\s*990/)
  await toggle.click()
  const members = main.locator('.cards-table__nested')
  await expect(members).toHaveCount(3)
  await expect(members.first()).toContainText('Samsung')
  await expect(members.last()).toContainText('Dyson')
  await selectMany(page, 'Маркетплейсы', ['Wildberries'])
  await page.getByRole('checkbox', { name: 'Только в наличии', exact: true }).check()
  await expect(group).toContainText('1 из 3 товаров')
  await expect(members).toHaveCount(1)
  await expect(members).toContainText('Sony')
  await expect(main).toContainText('Выбрано 1 из 7 товаров')
  await page.getByRole('button', { name: 'Изменить группу Контейнер', exact: true }).click()
  const edit = page.getByRole('dialog', { name: 'Изменить группу', exact: true })
  await expect(edit).toContainText('Выбрано карточек: 3')
  await edit.getByRole('button', { name: 'Сохранить', exact: true }).click()
  await expect(edit).toHaveCount(0)
  await selectMany(page, 'Маркетплейсы', ['Ozon'])
  await selectMany(page, 'Теги', ['Для дома'])
  await expect(group).toHaveCount(0)
  await expect(main).toContainText('Выбрано 0 из 7 товаров')
  await expect(main).toContainText('По выбранным условиям ничего не найдено')
  await main.getByRole('button', { name: 'Сбросить', exact: true }).click()
  await expect(group).toContainText('3 из 3 товаров')
  await expect(main).toContainText('Выбрано 7 из 7 товаров')
  expect(errors).toEqual([])
})

