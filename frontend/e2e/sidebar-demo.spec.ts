import { expect, test } from '@playwright/test'

test('два варианта сохраняют единый каталог, фильтры и работающую форму группы', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/cards?sidebar=1')
  const sidebar = page.getByRole('complementary', { name: 'Боковая панель', exact: true })
  const main = page.getByRole('main')
  await expect(main.getByRole('heading', { name: 'Карточки', exact: true })).toBeVisible()
  await expect(sidebar.getByLabel('Поиск карточек', { exact: true })).toHaveCount(0)
  await main.getByLabel('Поиск карточек', { exact: true }).fill('Samsung')
  await main.getByRole('combobox', { name: 'Сортировка', exact: true }).click()
  await page.getByRole('option', { name: 'Сначала дороже', exact: true }).click()
  await main.getByRole('radio', { name: 'Сетка', exact: true }).click()
  await expect(main).toContainText('1 из 5')

  await page.getByRole('radio', { name: 'Вариант 2', exact: true }).click()
  await expect(sidebar.getByLabel('Поиск карточек', { exact: true })).toHaveValue('Samsung')
  await expect(sidebar.getByRole('combobox', { name: 'Сортировка', exact: true })).toContainText('Сначала дороже')
  await expect(main.getByLabel('Поиск карточек', { exact: true })).toHaveCount(0)
  await expect(main.getByRole('radio', { name: 'Сетка', exact: true })).toBeChecked()
  await expect(main).toContainText('1 из 5')
  await sidebar.getByRole('button', { name: 'Создать группу', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Создать группу', exact: true })
  await dialog.getByRole('textbox', { name: 'Название', exact: true }).fill('Демо группа')
  await dialog.getByRole('checkbox', { name: /Смартфон Samsung/ }).check()
  await dialog.getByRole('button', { name: 'Сохранить', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await main.getByRole('button', { name: 'Сбросить', exact: true }).click()
  await expect(page).toHaveURL(/sidebar=2/)
  await expect(main.getByText('Демо группа', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.locator('.sidebar-demo')).toHaveAttribute('data-variant', '2')
  await expect(sidebar.getByRole('combobox', { name: 'Сортировка', exact: true })).toBeVisible()
  expect(errors).toEqual([])
})

for (const viewport of [{ width: 1440, height: 900 }, { width: 1024, height: 768 }]) {
  test(`прогресс закреплён снизу и проверка завершается при ${viewport.width}px`, async ({ page }) => {
    await page.setViewportSize(viewport)
    await page.goto('/cards?sidebar=2')
    const sidebar = page.getByRole('complementary', { name: 'Боковая панель', exact: true })
    await sidebar.getByRole('button', { name: 'Обновить все цены', exact: true }).click()
    const panel = sidebar.getByRole('complementary', { name: 'Состояние обновления цен', exact: true })
    await expect(panel).toBeVisible()
    await expect(sidebar.getByRole('button', { name: 'Обновить все цены', exact: true })).toBeDisabled()

    async function expectAnchored() {
      const parent = await sidebar.boundingBox()
      const box = await panel.boundingBox()
      expect(box).not.toBeNull()
      expect(box!.x).toBe(parent!.x)
      expect(Math.abs(box!.width - parent!.width)).toBeLessThanOrEqual(1)
      expect(Math.abs(box!.y + box!.height - viewport.height)).toBeLessThanOrEqual(1)
      expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(viewport.width)
    }

    await expectAnchored()
    await sidebar.locator('.sidebar-demo__scroll').evaluate((element) => { element.scrollTop = element.scrollHeight })
    await expectAnchored()
    await expect(panel.getByRole('button', { name: 'Проверка пройдена', exact: true })).toBeVisible({ timeout: 12000 })
    await expectAnchored()
    await page.getByRole('radio', { name: 'Вариант 1', exact: true }).click()
    await expectAnchored()
    await panel.getByRole('button', { name: 'Проверка пройдена', exact: true }).click()
    await expect(panel).toContainText('Цены обновлены', { timeout: 10000 })
    await panel.getByRole('button', { name: 'Закрыть', exact: true }).click()
    await expect(panel).toHaveCount(0)
  })
}

test('общие действия доступны в деталях товара, desktop-действия явно симулируются', async ({ page }) => {
  await page.goto('/cards?sidebar=2')
  await page.getByRole('link', { name: 'Смартфон Samsung Galaxy S24', exact: true }).click()
  const sidebar = page.getByRole('complementary', { name: 'Боковая панель', exact: true })
  await expect(sidebar).toBeVisible()
  await sidebar.getByRole('button', { name: 'Добавить карточку', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await sidebar.getByRole('button', { name: 'Открыть Chrome', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Браузер магазина' })).toContainText('В демо браузер не запускается')
  await page.getByRole('button', { name: 'Готово', exact: true }).click()
  await sidebar.getByRole('button', { name: 'Настройки', exact: true }).click()
  await page.getByRole('checkbox', { name: 'Запускать после входа в систему', exact: true }).check()
  await expect(page.getByRole('dialog')).toContainText('Закрытие окна оставляет сбор работающим в фоне')
})
