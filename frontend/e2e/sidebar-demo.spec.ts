import { expect, test } from '@playwright/test'

async function choose(page: import('@playwright/test').Page, control: string, option: string) {
  await page.getByRole('combobox', { name: control, exact: true }).click()
  await page.getByRole('option', { name: option, exact: true }).click()
}

async function selectMany(page: import('@playwright/test').Page, control: string, all: string, labels: string[]) {
  await page.getByRole('button', { name: control, exact: true }).click()
  const group = page.getByRole('group', { name: control, exact: true })
  await group.getByRole('checkbox', { name: all, exact: true }).uncheck()
  for (const label of labels) await group.getByRole('checkbox', { name: label, exact: true }).check()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: control, exact: true })).toBeFocused()
}

test('поиск над результатами работает по артикулу; группы, сетка и контекст сохраняются', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/cards?sidebar=2')
  const sidebar = page.getByRole('complementary', { name: 'Боковая панель', exact: true })
  const main = page.getByRole('main')
  await expect(main.getByRole('heading', { name: 'Карточки', exact: true })).toHaveCount(0)
  await expect(page.getByText('Текущие цены и история отслеживаемых карточек', { exact: true })).toHaveCount(0)
  await expect(page.getByRole('radio', { name: 'Вариант 1', exact: true })).toHaveCount(0)
  const search = main.getByPlaceholder('Название или артикул')
  await expect(sidebar.getByRole('textbox')).toHaveCount(0)
  await search.fill('234567890')
  await expect(main).toContainText('1 из 7')
  await expect(main.getByRole('link', { name: 'Наушники Sony WH-1000XM5', exact: true })).toBeVisible()
  await main.getByRole('radio', { name: 'Сетка', exact: true }).click()
  await main.getByRole('link', { name: 'Наушники Sony WH-1000XM5', exact: true }).click()
  await page.getByRole('link', { name: /К карточкам/ }).click()
  await expect(main.getByPlaceholder('Название или артикул')).toHaveValue('234567890')
  await expect(main.getByRole('radio', { name: 'Сетка', exact: true })).toBeChecked()
  await sidebar.getByRole('button', { name: 'Создать группу', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Создать группу', exact: true })
  await dialog.getByRole('textbox', { name: 'Название', exact: true }).fill('Демо группа')
  await dialog.getByRole('checkbox', { name: /Наушники Sony/ }).check()
  await dialog.getByRole('button', { name: 'Сохранить', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await main.getByRole('button', { name: 'Сбросить', exact: true }).click()
  await expect(main.getByText('Демо группа', { exact: true })).toBeVisible()
  expect(errors).toEqual([])
})

test('несколько площадок и OR-теги работают вместе и сохраняются после перезагрузки', async ({ page }) => {
  await page.goto('/cards?sidebar=2')
  const main = page.getByRole('main')
  await expect(main).toContainText('7 из 7')
  await selectMany(page, 'Маркетплейсы', 'Все маркетплейсы', ['Wildberries', 'AliExpress'])
  await expect(main).toContainText('2 из 7')
  await selectMany(page, 'Теги', 'Все теги', ['Для дома', 'Для себя'])
  await expect(main).toContainText('2 из 7')
  await expect(main).toContainText('Sony')
  await expect(main).toContainText('Roborock')
  await page.reload()
  await expect(main).toContainText('2 из 7')
  await expect(page.getByRole('button', { name: 'Теги', exact: true })).toContainText('Выбрано: 2')
  await expect(page.getByRole('button', { name: 'Маркетплейсы', exact: true })).toContainText('Выбрано: 2')
  await main.getByRole('button', { name: 'Сбросить', exact: true }).click()
  await expect(main).toContainText('7 из 7')
  await selectMany(page, 'Теги', 'Все теги', ['Для дома', 'Для себя'])
  await expect(main).toContainText('4 из 7')
  await page.getByRole('button', { name: 'Теги', exact: true }).click()
  await page.getByRole('group', { name: 'Теги', exact: true }).getByRole('checkbox', { name: 'Все теги', exact: true }).check()
  await page.keyboard.press('Escape')
  await expect(main).toContainText('7 из 7')
})

test('наличие исключает неизвестные данные; цена сортируется без приоритета выгодных', async ({ page }) => {
  await page.goto('/cards?sidebar=2')
  const main = page.getByRole('main')
  await expect(main).toContainText('7 из 7')
  await expect(page.getByRole('combobox', { name: 'Сортировка', exact: true })).toContainText('Сначала выгодные')
  await expect(main.getByRole('columnheader').getByRole('button')).toHaveCount(0)
  await page.getByRole('checkbox', { name: 'Только в наличии', exact: true }).check()
  await expect(main).toContainText('5 из 7')
  await expect(main.getByRole('link', { name: /Dyson/ })).toHaveCount(0)
  await expect(main.getByRole('link', { name: /Xiaomi/ })).toHaveCount(0)
  await page.getByRole('checkbox', { name: 'Только в наличии', exact: true }).uncheck()
  await choose(page, 'Сортировка', 'Сначала дешёвые')
  await expect(main.locator('tbody tr').first()).toContainText('Xiaomi')
  await expect(main.locator('tbody tr').last()).toContainText('Dyson')
  await choose(page, 'Сортировка', 'Сначала дорогие')
  await expect(main.locator('tbody tr').first()).toContainText('Samsung')
  await expect(main.locator('tbody tr').nth(1)).toContainText('LEGO')
  await expect(main.locator('tbody tr').last()).toContainText('Dyson')
  await choose(page, 'Выгодность', 'Выгодные')
  await expect(main).toContainText('1 из 7')
  await choose(page, 'Выгодность', 'Невыгодные')
  await expect(main).toContainText('6 из 7')
  await choose(page, 'Выгодность', 'Все предложения')
  await expect(main).toContainText('7 из 7')
})

for (const viewport of [{ width: 1440, height: 900 }, { width: 1024, height: 768 }]) {
  test(`прогресс закреплён снизу и проверка завершается при ${viewport.width}px`, async ({ page }) => {
    await page.setViewportSize(viewport)
    await page.goto('/cards?sidebar=2')
    const sidebar = page.getByRole('complementary', { name: 'Боковая панель', exact: true })
    await sidebar.getByRole('button', { name: 'Обновить все цены', exact: true }).click()
    const panel = sidebar.getByRole('complementary', { name: 'Состояние обновления цен', exact: true })
    await expect(panel).toBeVisible()
    await expect(sidebar.getByRole('button', { name: 'Обновить все цены', exact: true })).toBeDisabled()

    async function expectAnchored() {
      const parent = await sidebar.boundingBox()
      const box = await panel.boundingBox()
      expect(box).not.toBeNull()
      expect(box!.x).toBe(parent!.x)
      expect(Math.abs(box!.width - parent!.width)).toBeLessThanOrEqual(1)
      expect(Math.abs(box!.y + box!.height - viewport.height)).toBeLessThanOrEqual(1)
      expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(viewport.width)
    }

    await expectAnchored()
    await sidebar.locator('.sidebar-demo__scroll').evaluate((element) => { element.scrollTop = element.scrollHeight })
    await expectAnchored()
    await expect(panel.getByRole('button', { name: 'Проверка пройдена', exact: true })).toBeVisible({ timeout: 12000 })
    await expectAnchored()
    await panel.getByRole('button', { name: 'Проверка пройдена', exact: true }).click()
    await expect(panel).toContainText('Цены обновлены', { timeout: 10000 })
    await panel.getByRole('button', { name: 'Закрыть', exact: true }).click()
    await expect(panel).toHaveCount(0)
  })
}

