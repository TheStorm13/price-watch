import { expect, test } from '@playwright/test'

test('personal settings and variant target highlight list and tile without changing savings', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  const now = Date.now()
  await page.clock.install({ time: now })
  await page.goto('/cards')
  await expect(page.getByRole('row', { name: /Смартфон Samsung Galaxy S24/ })).toBeVisible()
  // The seed contains 27 days; four more days make historical rules eligible.
  await page.clock.setSystemTime(now + 4 * 86400000)
  await page.getByRole('button', { name: 'Настройки', exact: true }).click()
  const settings = page.getByRole('dialog', { name: 'Настройки', exact: true })
  await settings.getByRole('checkbox', { name: 'Небольшие колебания цены' }).check()
  await settings.getByLabel('Допустимая разница, ₽').fill('500000')
  await settings.getByRole('checkbox', { name: 'Доля максимальной выгоды', exact: true }).check()
  await settings.getByLabel('Доля выгоды, %').fill('70')
  await settings.getByRole('button', { name: 'Сохранить условия' }).click()
  await expect(settings.getByRole('button', { name: 'Сохранить условия' })).toBeEnabled()
  await page.keyboard.press('Escape')
  const row = page.getByRole('row', { name: /Смартфон Samsung Galaxy S24/ })
  await expect(row.getByRole('button', { name: 'Почему товар подходит для покупки' })).toBeVisible()
  await row.getByRole('button', { name: 'Почему товар подходит для покупки' }).click()
  await expect(page.getByText('Подходит по вашим условиям')).toBeVisible()
  await page.keyboard.press('Escape')
  await page.getByRole('link', { name: 'Смартфон Samsung Galaxy S24', exact: true }).click()
  await page.getByLabel('Куплю за, ₽').fill('80000')
  await page.getByRole('button', { name: 'Сохранить целевую цену' }).click()
  await expect(page.getByRole('status')).toContainText('Целевая цена сохранена')
  for (const days of ['7', '90']) {
    await page.getByRole('radio', { name: `${days} дней`, exact: true }).click()
    await expect(page.getByLabel('Куплю за, ₽')).toHaveValue('80000')
  }
  await page.getByRole('link', { name: 'К товарам', exact: true }).click()
  await row.getByRole('button', { name: 'Почему товар подходит для покупки' }).click()
  await expect(page.getByText(/не выше вашей целевой цены/)).toBeVisible()
  await page.keyboard.press('Escape')
  const savings = await row.locator('.catalog-savings').innerText()
  await page.getByRole('radio', { name: 'Сетка', exact: true }).click()
  const tile = page.locator('.cards-grid__item').filter({ has: page.getByText('Смартфон Samsung Galaxy S24', { exact: true }) })
  await expect(tile.getByRole('button', { name: 'Почему товар подходит для покупки' })).toBeVisible()
  expect(await tile.locator('.catalog-savings').innerText()).toEqual(savings)
  await tile.getByRole('button', { name: 'Почему товар подходит для покупки' }).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByText(/не выше вашей целевой цены/)).toBeVisible()
  await page.keyboard.press('Escape')
  expect(errors).toEqual([])
})
